/**
 * Feather-style icons, inlined so the app ships zero icon dependencies.
 * Every icon inherits `currentColor` and sizes from the `size` prop.
 */
type IconProps = React.ComponentProps<"svg"> & { size?: number };

function Icon({ size = 24, children, ...props }: IconProps) {
  return (
    <svg
      xmlns="http://www.w3.org/2000/svg"
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
      {...props}
    >
      {children}
    </svg>
  );
}

